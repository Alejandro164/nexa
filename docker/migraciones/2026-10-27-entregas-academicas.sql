-- ════════════════════════════════════════════════════════════════════════════
-- Entregas académicas: la dirección define entregas con plazo (planeamiento, informes, etc.),
-- cada docente las prepara como borrador, las presenta y la dirección las aprueba o las devuelve.
--
-- Prod usa spring.jpa.hibernate.ddl-auto=validate, así que esto debe aplicarse
-- ANTES de desplegar la versión con Entregas académicas. En dev no hace falta:
-- Hibernate crea las tablas (ddl-auto=update).
--
-- Es idempotente: se puede ejecutar más de una vez.
-- Uso (en el servidor de prod):
--   psql -h localhost -U <usuario> -d <base> -v ON_ERROR_STOP=1 -f 2026-10-27-entregas-academicas.sql
-- ════════════════════════════════════════════════════════════════════════════

BEGIN;

CREATE TABLE IF NOT EXISTS entregas_academicas (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direccion_id    bigint       NOT NULL REFERENCES direcciones (id),
    nombre          varchar(200) NOT NULL,
    descripcion     varchar(1000),
    tipo            varchar(20)  NOT NULL
        CHECK (tipo IN ('PLANEAMIENTO', 'INFORME', 'EVALUACION', 'ADMINISTRATIVA', 'OTRA')),
    periodo_id      bigint REFERENCES periodos_academicos (id),
    fecha_inicio    date         NOT NULL,
    fecha_fin       date         NOT NULL,
    activa          boolean      NOT NULL DEFAULT true,
    creado_por_id   bigint       NOT NULL REFERENCES usuarios (id),
    fecha_creacion  timestamp(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_entregas_academicas_direccion ON entregas_academicas (direccion_id, fecha_inicio);

CREATE TABLE IF NOT EXISTS entregas_academicas_docente (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entrega_id            bigint       NOT NULL REFERENCES entregas_academicas (id),
    docente_id            bigint       NOT NULL REFERENCES usuarios (id),
    estado                varchar(12)  NOT NULL
        CHECK (estado IN ('BORRADOR', 'PRESENTADA', 'DEVUELTA', 'APROBADA')),
    observacion           varchar(2000),
    observacion_revision  varchar(1000),
    fecha_creacion        timestamp(6) NOT NULL,
    fecha_presentacion    timestamp(6),
    fecha_revision        timestamp(6),
    revisado_por_id       bigint REFERENCES usuarios (id),
    CONSTRAINT uk_entrega_academica_docente UNIQUE (entrega_id, docente_id)
);
CREATE INDEX IF NOT EXISTS idx_entregas_academicas_docente_docente ON entregas_academicas_docente (docente_id);

CREATE TABLE IF NOT EXISTS adjuntos_entrega_academica (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    presentacion_id  bigint       NOT NULL REFERENCES entregas_academicas_docente (id),
    nombre           varchar(255) NOT NULL,
    ruta             varchar(500),
    url              varchar(1000),
    extension        varchar(20),
    tamano_bytes     bigint,
    fecha_creacion   timestamp(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_adjuntos_entrega_academica_presentacion ON adjuntos_entrega_academica (presentacion_id);

COMMIT;
