-- ════════════════════════════════════════════════════════════════════════════
-- Tabla de prematrículas y borradores de matrícula de estudiantes.
--
-- Separa el ciclo previo a la matrícula oficial (PREMATRICULA y BORRADOR) de la
-- tabla usuarios (Expedientes), evitando que aspirantes o trámites incompletos
-- aparezcan en asistencia, notas, classroom o inicio de sesión antes de
-- completar su matrícula.
--
-- Requiere haber aplicado antes 2026-11-26-anio-matricula-estudiantes.sql.
--
-- Prod usa spring.jpa.hibernate.ddl-auto=validate, así que esto debe aplicarse
-- ANTES de desplegar esta versión. En dev Hibernate crea la tabla al arrancar.
--
-- Es idempotente: se puede ejecutar más de una vez.
-- Uso (en el servidor de prod):
--   psql -h localhost -U <usuario> -d <base> -v ON_ERROR_STOP=1 -f 2026-11-26-matriculas-estudiantes.sql
-- ════════════════════════════════════════════════════════════════════════════

BEGIN;

CREATE TABLE IF NOT EXISTS matriculas_estudiantes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direccion_id bigint NOT NULL REFERENCES direcciones(id),
    estado varchar(20) NOT NULL,
    nombre varchar(100) NOT NULL,
    cedula varchar(30),
    email varchar(150),
    usuario varchar(60),
    password_hash varchar(255),
    nivel_academico_id bigint REFERENCES niveles_academicos(id),
    anio_matricula integer NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    estudiante_id bigint REFERENCES usuarios(id),
    fecha_creacion timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT matriculas_estudiantes_estado_check
        CHECK (estado IN ('PREMATRICULA', 'BORRADOR', 'COMPLETADA')),
    CONSTRAINT matriculas_estudiantes_anio_check
        CHECK (anio_matricula BETWEEN 1990 AND 2100)
);

CREATE INDEX IF NOT EXISTS idx_matriculas_est_dir_estado
    ON matriculas_estudiantes (direccion_id, estado);

CREATE INDEX IF NOT EXISTS idx_matriculas_est_cedula
    ON matriculas_estudiantes (direccion_id, cedula);

COMMIT;
