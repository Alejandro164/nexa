-- Comunicados: destinatarios internos de los oficios y registro de lectura
--
-- Prod usa spring.jpa.hibernate.ddl-auto=validate, así que esto debe aplicarse
-- ANTES de desplegar la versión con Comunicados. En dev no hace falta:
-- Hibernate crea las tablas y la columna nueva (ddl-auto=update) y
-- DatabaseIndexInitializer quita el NOT NULL de la dirección destinataria.
--
-- Es idempotente: se puede ejecutar más de una vez.
-- Uso (en el servidor de prod):
--   psql -h localhost -U <usuario> -d <base> -v ON_ERROR_STOP=1 -f 2026-10-13-comunicados.sql
-- ════════════════════════════════════════════════════════════════════════════

BEGIN;

-- La dirección destinataria externa es opcional: un oficio puede dirigirse solo a personas o grupos internos.
ALTER TABLE oficios ALTER COLUMN destinatario_direccion_id DROP NOT NULL;

-- Momento exacto de la emisión (la columna "fecha" solo guarda el día).
ALTER TABLE oficios ADD COLUMN IF NOT EXISTS fecha_emision timestamp(6);

-- A quién ve el oficio en Comunicados. Según el tipo se usa usuario_id (PERSONA) o nivel_id (FAMILIAS_SECCION).
CREATE TABLE IF NOT EXISTS oficio_destinatarios (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oficio_id   bigint NOT NULL REFERENCES oficios (id),
    tipo        varchar(20) NOT NULL
                CONSTRAINT oficio_destinatarios_tipo_check
                CHECK (tipo IN ('COMUNIDAD', 'DOCENTES', 'FAMILIAS', 'ESTUDIANTES', 'FAMILIAS_SECCION', 'PERSONA')),
    usuario_id  bigint REFERENCES usuarios (id),
    nivel_id    bigint REFERENCES niveles_academicos (id)
);
CREATE INDEX IF NOT EXISTS idx_oficio_destinatario_oficio ON oficio_destinatarios (oficio_id);

-- Primera vez que cada persona abrió o descargó el documento del oficio.
CREATE TABLE IF NOT EXISTS oficio_lecturas (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oficio_id   bigint NOT NULL REFERENCES oficios (id),
    usuario_id  bigint NOT NULL REFERENCES usuarios (id),
    fecha       timestamp(6) NOT NULL,
    CONSTRAINT uk_oficio_lectura UNIQUE (oficio_id, usuario_id)
);

COMMIT;
