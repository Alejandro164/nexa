-- ════════════════════════════════════════════════════════════════════════════
-- Mensajería directa (Comunicación > Mensajes): conversaciones, mensajes y reacciones
--
-- Prod usa spring.jpa.hibernate.ddl-auto=validate, así que estas tablas deben
-- existir ANTES de desplegar la versión con la mensajería.
-- En dev no hace falta: Hibernate las crea solo (ddl-auto=update).
--
-- Es idempotente: si las tablas ya existen no se tocan.
-- Uso (en el servidor de prod):
--   psql -h localhost -U <usuario> -d <base> -v ON_ERROR_STOP=1 -f 2026-10-12-mensajeria.sql
-- ════════════════════════════════════════════════════════════════════════════

BEGIN;

-- Conversación 1 a 1 dentro de una dirección. El par se guarda ordenado por id
-- (usuario_a_id < usuario_b_id) y el último mensaje leído de cada lado vive aquí.
CREATE TABLE IF NOT EXISTS mensajeria_conversaciones (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direccion_id          bigint NOT NULL REFERENCES direcciones (id),
    usuario_a_id          bigint NOT NULL REFERENCES usuarios (id),
    usuario_b_id          bigint NOT NULL REFERENCES usuarios (id),
    ultimo_leido_a        bigint NOT NULL DEFAULT 0,
    ultimo_leido_b        bigint NOT NULL DEFAULT 0,
    fecha_creacion        timestamp(6) NOT NULL,
    fecha_ultimo_mensaje  timestamp(6) NOT NULL,
    CONSTRAINT uk_mensajeria_conversacion_par UNIQUE (direccion_id, usuario_a_id, usuario_b_id)
);
CREATE INDEX IF NOT EXISTS idx_mensajeria_conversacion_a ON mensajeria_conversaciones (usuario_a_id);
CREATE INDEX IF NOT EXISTS idx_mensajeria_conversacion_b ON mensajeria_conversaciones (usuario_b_id);

-- Texto, un archivo adjunto (documento o foto) o ambos. archivo_ruta es relativa a ruta.recursos.
CREATE TABLE IF NOT EXISTS mensajeria_mensajes (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversacion_id         bigint NOT NULL REFERENCES mensajeria_conversaciones (id),
    autor_id                bigint NOT NULL REFERENCES usuarios (id),
    texto                   varchar(4000),
    respuesta_a_id          bigint REFERENCES mensajeria_mensajes (id),
    fecha                   timestamp(6) NOT NULL,
    archivo_ruta            varchar(500),
    archivo_nombre          varchar(255),
    archivo_tipo_contenido  varchar(100),
    archivo_tamano          bigint,
    archivo_imagen          boolean
);
CREATE INDEX IF NOT EXISTS idx_mensajeria_mensaje_conversacion ON mensajeria_mensajes (conversacion_id, id);

-- Una persona reacciona una vez por emoji a cada mensaje.
CREATE TABLE IF NOT EXISTS mensajeria_reacciones (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mensaje_id  bigint NOT NULL REFERENCES mensajeria_mensajes (id),
    usuario_id  bigint NOT NULL REFERENCES usuarios (id),
    emoji       varchar(16) NOT NULL,
    CONSTRAINT uk_mensajeria_reaccion UNIQUE (mensaje_id, usuario_id, emoji)
);

COMMIT;
