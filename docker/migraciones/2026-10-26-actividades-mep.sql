-- Agenda > Actividad Institucional: la institución elige cuáles actividades del calendario
-- del MEP incluye en su calendario (y puede ponerles un título corto personalizado).
--
-- Prod usa spring.jpa.hibernate.ddl-auto=validate, así que esto debe aplicarse
-- ANTES de desplegar la versión con actividades MEP seleccionadas. En dev no hace falta:
-- Hibernate crea la tabla (ddl-auto=update).
--
-- Es idempotente: se puede ejecutar más de una vez.
-- Uso (en el servidor de prod):
--   psql -h localhost -U <usuario> -d <base> -v ON_ERROR_STOP=1 -f 2026-10-26-actividades-mep.sql
-- ════════════════════════════════════════════════════════════════════════════

BEGIN;

CREATE TABLE IF NOT EXISTS actividades_mep_seleccionadas (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mep_evento_id        varchar(100) NOT NULL,
    anio                 integer      NOT NULL,
    titulo_personalizado varchar(200),
    direccion_id         bigint       NOT NULL REFERENCES direcciones (id),
    seleccionado_por_id  bigint       NOT NULL REFERENCES usuarios (id),
    fecha_seleccion      timestamp(6) NOT NULL,
    CONSTRAINT uk_actividad_mep_direccion_anio_evento UNIQUE (direccion_id, anio, mep_evento_id)
);

-- Por si la tabla ya existía sin el título personalizado
ALTER TABLE actividades_mep_seleccionadas ADD COLUMN IF NOT EXISTS titulo_personalizado varchar(200);

COMMIT;
