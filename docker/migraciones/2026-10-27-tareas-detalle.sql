-- ════════════════════════════════════════════════════════════════════════════
-- Agenda: detalle de tarea (etiquetas, fechas con recordatorio, checklist, miembros,
-- adjuntos, comentarios/actividad) y nuevos estados de tarea.
--
-- Estados de tarea (enum en Java, columna varchar):
--   PENDIENTE      -> PENDIENTE
--   EN_PROGRESO    -> EN_EJECUCION
--   COMPLETADA     -> FINALIZADO
--   VENCIDA        -> PENDIENTE     (ya no es un estado: "vencida" se calcula por la fecha límite)
--   nuevos: EN_REVISION, EN_CORRECCION
--
-- Prod usa spring.jpa.hibernate.ddl-auto=validate, así que esto debe aplicarse
-- ANTES de desplegar la versión con el detalle de tarea. En dev también conviene
-- aplicarlo antes de levantar la app: los valores viejos de estado no se pueden leer
-- con el enum nuevo.
--
-- Es idempotente: se puede ejecutar más de una vez. Conserva todos los datos.
-- Uso (en el servidor de prod):
--   psql -h localhost -U <usuario> -d <base> -v ON_ERROR_STOP=1 -f 2026-10-27-tareas-detalle.sql
-- Requiere haber aplicado antes 2026-10-26-plan-trabajo.sql (tareas_plan_trabajo).
-- ════════════════════════════════════════════════════════════════════════════

BEGIN;

-- ── Estados ─────────────────────────────────────────────────────────────────
ALTER TABLE tareas_plan_trabajo DROP CONSTRAINT IF EXISTS tareas_plan_trabajo_estado_check;
ALTER TABLE tareas_plan_trabajo ALTER COLUMN estado TYPE varchar(20);

UPDATE tareas_plan_trabajo SET estado = 'EN_EJECUCION' WHERE estado = 'EN_PROGRESO';
UPDATE tareas_plan_trabajo SET estado = 'FINALIZADO'   WHERE estado = 'COMPLETADA';
UPDATE tareas_plan_trabajo SET estado = 'PENDIENTE'    WHERE estado = 'VENCIDA';

ALTER TABLE tareas_plan_trabajo ADD CONSTRAINT tareas_plan_trabajo_estado_check
    CHECK (estado IN ('PENDIENTE', 'EN_EJECUCION', 'EN_REVISION', 'EN_CORRECCION', 'FINALIZADO'));

-- ── Fechas y recordatorio ───────────────────────────────────────────────────
ALTER TABLE tareas_plan_trabajo ADD COLUMN IF NOT EXISTS fecha_inicio date;
ALTER TABLE tareas_plan_trabajo ADD COLUMN IF NOT EXISTS recordatorio varchar(20) NOT NULL DEFAULT 'NINGUNO';
ALTER TABLE tareas_plan_trabajo ADD COLUMN IF NOT EXISTS recordatorio_enviado boolean NOT NULL DEFAULT false;

ALTER TABLE tareas_plan_trabajo DROP CONSTRAINT IF EXISTS tareas_plan_trabajo_recordatorio_check;
ALTER TABLE tareas_plan_trabajo ADD CONSTRAINT tareas_plan_trabajo_recordatorio_check
    CHECK (recordatorio IN ('NINGUNO', 'AL_VENCER', 'UN_DIA_ANTES', 'DOS_DIAS_ANTES', 'UNA_SEMANA_ANTES'));

-- ── Etiquetas (catálogo por dirección) ──────────────────────────────────────
CREATE TABLE IF NOT EXISTS etiquetas_tarea (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       varchar(60) NOT NULL,
    color        varchar(7)  NOT NULL,
    direccion_id bigint      NOT NULL REFERENCES direcciones (id),
    CONSTRAINT uk_etiqueta_tarea_direccion_nombre UNIQUE (direccion_id, nombre)
);

CREATE TABLE IF NOT EXISTS tareas_plan_trabajo_etiquetas (
    tarea_id    bigint NOT NULL REFERENCES tareas_plan_trabajo (id),
    etiqueta_id bigint NOT NULL REFERENCES etiquetas_tarea (id),
    PRIMARY KEY (tarea_id, etiqueta_id)
);

-- ── Miembros adicionales (colaboradores) ────────────────────────────────────
CREATE TABLE IF NOT EXISTS tareas_plan_trabajo_colaboradores (
    tarea_id   bigint NOT NULL REFERENCES tareas_plan_trabajo (id),
    usuario_id bigint NOT NULL REFERENCES usuarios (id),
    PRIMARY KEY (tarea_id, usuario_id)
);

-- ── Checklist ───────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS checklist_items_tarea (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarea_id   bigint       NOT NULL REFERENCES tareas_plan_trabajo (id),
    texto      varchar(300) NOT NULL,
    completado boolean      NOT NULL DEFAULT false,
    orden      integer      NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_checklist_items_tarea_tarea ON checklist_items_tarea (tarea_id);

-- ── Adjuntos (archivo en disco o enlace) ────────────────────────────────────
CREATE TABLE IF NOT EXISTS adjuntos_tarea (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarea_id       bigint       NOT NULL REFERENCES tareas_plan_trabajo (id),
    nombre         varchar(255) NOT NULL,
    ruta           varchar(500),
    url            varchar(1000),
    extension      varchar(20),
    tamano_bytes   bigint,
    subido_por_id  bigint REFERENCES usuarios (id),
    fecha_creacion timestamp(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_adjuntos_tarea_tarea ON adjuntos_tarea (tarea_id);

-- ── Comentarios y actividad ─────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS actividad_tarea (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarea_id   bigint        NOT NULL REFERENCES tareas_plan_trabajo (id),
    usuario_id bigint        NOT NULL REFERENCES usuarios (id),
    tipo       varchar(12)   NOT NULL CHECK (tipo IN ('COMENTARIO', 'ACTIVIDAD')),
    texto      varchar(2000) NOT NULL,
    fecha      timestamp(6)  NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_actividad_tarea_tarea ON actividad_tarea (tarea_id);

COMMIT;
